--- Экранирование текста для HTML.
---
--- Экранируется всё, что уходит в страницу: текст абзаца, содержимое
--- ограды кода, адрес ссылки, подпись. Знаков пять, и больше не надо:
--- экранировать остальное значило бы портить кириллицу и пунктуацию
--- сущностями без нужды.
---
--- Образец ловит любой знак препинания, а что заменять, решает одна
--- таблица: знака, которого в ней нет, замена не касается. Набор знаков
--- в самом образце обязан был бы совпадать с таблицей, и лишний знак
--- в нём ничего бы не изменил — такую ошибку не видно ни одной проверкой.

local Module = {}

--- Чем заменяется каждый из пяти знаков.
local ESCAPED = { ['&'] = '&amp;', ['<'] = '&lt;', ['>'] = '&gt;', ['"'] = '&quot;', ["'"] = '&#39;' }

--- Экранирует текст для HTML.
---@param text string
---@return string
function Module.html(text)
    return (text:gsub('%p', ESCAPED))
end

return Module
